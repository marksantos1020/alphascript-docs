import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = resolve(root, process.env.ALPHASCRIPT_DIR ?? "../alphaforge-frontend/packages/alphascript");
const library = resolve(pkg, "../../src/chart/library.ts");
const check = process.argv.includes("--check");
for (const p of [join(pkg, "examples"), join(pkg, "indicators"), library]) {
  if (!existsSync(p)) { console.error(`${p} not found; set ALPHASCRIPT_DIR to the alphascript package`); process.exit(1); }
}

const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const lib = read(library);
const recordOf = (name) => {
  const body = new RegExp(`const ${name}[^=]*=\\s*\\{([\\s\\S]*?)\\n\\};`).exec(lib)?.[1] ?? "";
  return body;
};
const META = Object.fromEntries([...recordOf("META").matchAll(/(\w+): \{ category: "([^"]+)", description: "([^"]+)" \}/g)]
  .map(([, id, category, description]) => [id, { category, description }]));
const NOTES = Object.fromEntries([...recordOf("STRATEGY_NOTES").matchAll(/(\w+): "([^"]+)"/g)].map(([, id, text]) => [id, text]));
const CATEGORY_ORDER = ["Moving averages", "Bands & channels", "Trend", "Oscillators", "Volume", "Chain"];

const field = (src, name) => new RegExp(`${name}:\\s*"([^"]*)"`).exec(src)?.[1];
const strip = (src) => src.split("\n").filter((l) => !/^\s*(\/\/ @ts-check|\/\/\/ <reference)/.test(l)).join("\n").trim();
const inputsOf = (src) => [...src.matchAll(/input\.(int|float|bool|select|string|source|color)\(\s*"([^"]+)",\s*("[^"]*"|[^,)]+)/g)]
  .map(([, type, name, def]) => ({ type, name, def: def.trim() }));

function load(dir) {
  return readdirSync(join(pkg, dir)).filter((f) => f.endsWith(".as.js")).sort().map((f) => {
    const id = f.replace(/\.as\.js$/, "");
    const src = strip(read(join(pkg, dir, f)));
    const kind = /^\s*strategy\s*\(/m.test(src) ? "strategy" : "indicator";
    return { id, file: `${dir}/${f}`, src, kind, name: field(src, "name") ?? id, resolution: field(src, "resolution"),
             overlay: /overlay:\s*true/.test(src), inputs: inputsOf(src) };
  });
}
const examples = load("examples");
const indicators = load("indicators");

const header = "<!-- GENERATED by scripts/gen-examples.mjs from alphaforge-frontend. Do not edit; run npm run gen. -->";
const cell = (s) => String(s).replace(/\|/g, "\\|");
const files = new Map();
const missingNotes = [];

function inputsTable(inputs) {
  if (!inputs.length) return [];
  return ["## Inputs", "", "| Input | Type | Default |", "| --- | --- | --- |",
    ...inputs.map((i) => `| ${cell(i.name)} | ${i.type} | \`${cell(i.def)}\` |`), ""];
}

function page(e, { summary, notesFile, howTo }) {
  const notePath = join(root, "notes/examples", `${notesFile}.md`);
  const notes = existsSync(notePath) ? read(notePath).trim() : null;
  if (!notes && notesFile) missingNotes.push(notesFile);
  const facts = e.kind === "strategy"
    ? [`**Kind** strategy`, `**Resolution** ${e.resolution ?? "chart"}`]
    : [`**Kind** indicator`, `**Drawn** ${e.overlay ? "on the price pane" : "in its own pane"}`];
  return [header, "", `# ${e.name}`, "", ...(summary ? [`*${summary}.*`, ""] : []), facts.join(" · "), "",
    ...(notes ? [notes, ""] : []),
    "## Try it", "", howTo, "",
    ...inputsTable(e.inputs),
    "## Source", "", `From \`packages/alphascript/${e.file}\`.`, "", "```js", e.src, "```", ""].join("\n");
}

for (const e of examples) {
  const howTo = e.kind === "strategy"
    ? `On the chart, press <kbd>/</kbd>, open **Strategies** and choose **${e.name}**. Or copy the source below into the AlphaScript editor and click **Add to chart**.`
    : "Copy the source below into the AlphaScript editor and click **Add to chart**.";
  files.set(`examples/${e.id}.md`, page(e, { summary: NOTES[e.id], notesFile: e.id, howTo }));
}
for (const e of indicators) {
  const howTo = `On the chart, press <kbd>/</kbd> and choose **${e.name}**${META[e.id] ? ` under **${META[e.id].category}**` : ""}. To change it, copy the source below into the AlphaScript editor.`;
  files.set(`examples/indicators/${e.id}.md`, page(e, { summary: META[e.id]?.description, notesFile: null, howTo }));
}

const strategies = examples.filter((e) => e.kind === "strategy");
const extraIndicators = examples.filter((e) => e.kind === "indicator");
const byCategory = new Map(CATEGORY_ORDER.map((c) => [c, []]));
for (const e of indicators) {
  const c = META[e.id]?.category ?? "Other";
  if (!byCategory.has(c)) byCategory.set(c, []);
  byCategory.get(c).push(e);
}
const index = [header, "", "# Examples", "",
  "Every example here is a script you can run: the strategies are in the chart's picker under **Strategies**, and the",
  "indicators are the chart's built-in indicators. The source on each page is the exact file the platform runs.", "",
  "## Strategies", "", "| Strategy | Resolution | What it does |", "| --- | --- | --- |",
  ...strategies.map((e) => `| [${cell(e.name)}](./${e.id}) | ${e.resolution ?? ""} | ${cell(NOTES[e.id] ?? "")} |`), "",
  ...(extraIndicators.length ? ["## Indicator examples", "", "| Indicator | What it shows |", "| --- | --- |",
    ...extraIndicators.map((e) => `| [${cell(e.name)}](./${e.id}) | ${cell(NOTES[e.id] ?? "")} |`), ""] : []),
  "## Built-in indicators", "",
  ...[...byCategory].filter(([, list]) => list.length).flatMap(([c, list]) => [`### ${c}`, "", "| Indicator | What it shows |", "| --- | --- |",
    ...list.map((e) => `| [${cell(e.name)}](./indicators/${e.id}) | ${cell(META[e.id]?.description ?? "")} |`), ""]),
].join("\n");
files.set("examples/index.md", index);

const sidebar = [
  { text: "Examples", link: "/examples/" },
  { text: "Strategies", items: strategies.map((e) => ({ text: e.name, link: `/examples/${e.id}` })) },
  ...(extraIndicators.length ? [{ text: "Indicator examples", items: extraIndicators.map((e) => ({ text: e.name, link: `/examples/${e.id}` })) }] : []),
  ...[...byCategory].filter(([, list]) => list.length).map(([c, list]) => ({
    text: c, collapsed: true, items: list.map((e) => ({ text: e.name, link: `/examples/indicators/${e.id}` })),
  })),
];
files.set("examples/sidebar.json", JSON.stringify(sidebar, null, 2) + "\n");

let stale = 0;
for (const [rel, body] of files) {
  const path = join(root, rel);
  const old = existsSync(path) ? readFileSync(path, "utf8").replace(/\r\n/g, "\n") : null;
  if (old === body) continue;
  if (check) { console.error(`out of date: ${rel}`); stale++; continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body);
}
if (check && stale) { console.error("run npm run gen"); process.exit(1); }
console.log(`examples: ${strategies.length} strategies, ${extraIndicators.length + indicators.length} indicators` +
  (missingNotes.length ? `; no notes for ${missingNotes.join(", ")}` : ""));
